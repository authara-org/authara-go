package authara

import (
	"encoding/json"
	"time"
)

// WebhookEvent represents a webhook event sent by Authara.
//
// Each event contains metadata (ID, type, timestamp) and a raw JSON
// payload in Data that can be decoded into a concrete event type.
type WebhookEvent struct {
	// ID is the unique identifier of the webhook event.
	//
	// It can be used for idempotency and deduplication when processing events.
	ID string `json:"id"`

	// Type identifies the type of event (e.g. "user.created").
	//
	// Applications should use this field to determine how to handle the event.
	Type string `json:"type"`

	// CreatedAt is the timestamp when the event was generated by Authara.
	//
	// This can be used for ordering or auditing purposes.
	CreatedAt time.Time `json:"created_at"`

	// Data contains the event-specific payload as raw JSON.
	//
	// It must be decoded into the appropriate struct depending on Type.
	Data json.RawMessage `json:"data"`
}

// RegistrationCompletedData is the complete initial identity snapshot for a
// "registration.completed" event.
type RegistrationCompletedData struct {
	UserID             string          `json:"user_id"`
	OrganizationID     string          `json:"organization_id"`
	OrganizationName   string          `json:"organization_name"`
	MembershipRole     string          `json:"membership_role"`
	MembershipMetadata json.RawMessage `json:"membership_metadata"`
}

// UserCreatedData is the payload for the "user.created" event.
//
// It contains information about the newly created user.
type UserCreatedData struct {
	// UserID is the unique identifier of the created user.
	UserID string `json:"user_id"`
}

// UserUpdatedData is the payload for the "user.updated" event.
type UserUpdatedData struct {
	UserID string `json:"user_id"`
}

// UserDeletedData is the payload for the "user.deleted" event.
//
// It contains information about the deleted user.
type UserDeletedData struct {
	// UserID is the unique identifier of the deleted user.
	UserID string `json:"user_id"`
}

// OrganizationData is the payload for organization lifecycle events.
type OrganizationData struct {
	OrganizationID  string  `json:"organization_id"`
	Name            string  `json:"name"`
	Kind            string  `json:"kind"`
	CreatedByUserID *string `json:"created_by_user_id"`
}

// OrganizationMembershipData is the payload for organization membership events.
type OrganizationMembershipData struct {
	OrganizationID string `json:"organization_id"`
	UserID         string `json:"user_id"`
	Role           string `json:"role"`
}

// OrganizationMembershipCreatedData is the payload for "organization.membership.created".
type OrganizationMembershipCreatedData struct {
	OrganizationID      string          `json:"organization_id"`
	UserID              string          `json:"user_id"`
	Role                string          `json:"role"`
	IsInitialMembership bool            `json:"is_initial_membership"`
	InvitationID        *string         `json:"invitation_id"`
	Metadata            json.RawMessage `json:"metadata"`
}

// OrganizationInvitationCreatedData is the payload for "organization.invitation.created".
type OrganizationInvitationCreatedData struct {
	InvitationID    string          `json:"invitation_id"`
	OrganizationID  string          `json:"organization_id"`
	Email           string          `json:"email"`
	Role            string          `json:"role"`
	Metadata        json.RawMessage `json:"metadata"`
	InvitedByUserID *string         `json:"invited_by_user_id"`
	ExpiresAt       time.Time       `json:"expires_at"`
}

// OrganizationInvitationAcceptedData is the payload for "organization.invitation.accepted".
type OrganizationInvitationAcceptedData struct {
	InvitationID     string          `json:"invitation_id"`
	OrganizationID   string          `json:"organization_id"`
	Email            string          `json:"email"`
	Role             string          `json:"role"`
	Metadata         json.RawMessage `json:"metadata"`
	AcceptedByUserID string          `json:"accepted_by_user_id"`
	AcceptedAt       time.Time       `json:"accepted_at"`
}

// OrganizationInvitationRevokedData is the payload for "organization.invitation.revoked".
type OrganizationInvitationRevokedData struct {
	InvitationID    string          `json:"invitation_id"`
	OrganizationID  string          `json:"organization_id"`
	Email           string          `json:"email"`
	Role            string          `json:"role"`
	Metadata        json.RawMessage `json:"metadata"`
	RevokedByUserID *string         `json:"revoked_by_user_id"`
	RevokedAt       time.Time       `json:"revoked_at"`
}
